#!/usr/bin/env bash
# One-time preparation of a fresh Ubuntu 22.04/24.04 cloud VM for StudentHub.
# Run it ON THE SERVER as a sudo-capable user:
#
#   sudo bash server-setup.sh \
#     --image ghcr.io/<github-user>/studenthub-assignment-tracker \
#     --site <your-ip-with-dashes>.sslip.io \
#     --pubkey "ssh-ed25519 AAAA... github-actions-deploy"
#
# What it does (safe to re-run; existing files and secrets are kept):
#   1. installs Docker Engine + the Compose plugin from Docker's official apt repository
#   2. creates a 'deploy' user that may run Docker, and authorises the given SSH public key
#   3. configures the UFW firewall: only SSH (22), HTTP (80) and HTTPS (443) are open
#   4. adds a 2 GB swap file on small VMs (helps MySQL on 1 GB instances)
#   5. creates /home/deploy/studenthub/.env with strong random passwords if it does not exist
set -Eeuo pipefail

IMAGE="" SITE="" PUBKEY="" DEPLOY_USER="deploy" TIMEZONE="Asia/Kolkata"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --image) IMAGE="$2"; shift 2 ;;
    --site) SITE="$2"; shift 2 ;;
    --pubkey) PUBKEY="$2"; shift 2 ;;
    --user) DEPLOY_USER="$2"; shift 2 ;;
    --timezone) TIMEZONE="$2"; shift 2 ;;
    *) echo "Unknown option: $1"; exit 1 ;;
  esac
done
[[ $EUID -eq 0 ]] || { echo "Run with sudo."; exit 1; }
[[ -n "$IMAGE" && -n "$SITE" && -n "$PUBKEY" ]] || { echo "Usage: sudo bash $0 --image <ghcr image> --site <address> --pubkey \"<ssh public key>\""; exit 1; }
IMAGE="$(echo "$IMAGE" | tr '[:upper:]' '[:lower:]')"

log() { printf '\n==> %s\n' "$*"; }

log "Installing Docker Engine and Compose plugin"
if ! command -v docker >/dev/null 2>&1; then
  apt-get update -y
  apt-get install -y ca-certificates curl gnupg
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  . /etc/os-release
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu ${VERSION_CODENAME} stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update -y
  apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
fi
systemctl enable --now docker
docker compose version

log "Creating user '$DEPLOY_USER' and authorising the deploy key"
id "$DEPLOY_USER" >/dev/null 2>&1 || adduser --disabled-password --gecos "" "$DEPLOY_USER"
usermod -aG docker "$DEPLOY_USER"
HOME_DIR="$(getent passwd "$DEPLOY_USER" | cut -d: -f6)"
install -d -m 700 -o "$DEPLOY_USER" -g "$DEPLOY_USER" "$HOME_DIR/.ssh"
touch "$HOME_DIR/.ssh/authorized_keys"
grep -qxF "$PUBKEY" "$HOME_DIR/.ssh/authorized_keys" || echo "$PUBKEY" >> "$HOME_DIR/.ssh/authorized_keys"
chown "$DEPLOY_USER:$DEPLOY_USER" "$HOME_DIR/.ssh/authorized_keys"
chmod 600 "$HOME_DIR/.ssh/authorized_keys"

log "Configuring firewall (UFW)"
apt-get install -y ufw
ufw allow OpenSSH
ufw allow 80/tcp
ufw allow 443/tcp
ufw allow 443/udp
ufw --force enable
ufw status verbose

log "Checking swap"
if [[ "$(swapon --show | wc -l)" -eq 0 && "$(awk '/MemTotal/ {print $2}' /proc/meminfo)" -lt 2500000 ]]; then
  fallocate -l 2G /swapfile && chmod 600 /swapfile && mkswap /swapfile && swapon /swapfile
  grep -q '/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
  echo "2 GB swap file created"
else
  echo "swap already present or enough memory"
fi

log "Preparing $HOME_DIR/studenthub"
APP_DIR="$HOME_DIR/studenthub"
install -d -m 750 -o "$DEPLOY_USER" -g "$DEPLOY_USER" "$APP_DIR" "$APP_DIR/backups"
if [[ ! -f "$APP_DIR/.env" ]]; then
  rand() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "$1"; }
  cat > "$APP_DIR/.env" <<EOF
# Production settings for StudentHub. Generated by server-setup.sh on $(date -u +%F).
# Keep this file private: it is never committed to Git.
IMAGE_NAME=${IMAGE}
IMAGE_TAG=main
SITE_ADDRESS=${SITE}
SECRET_KEY=$(rand 64)
MYSQL_DATABASE=studenthub
MYSQL_USER=studenthub
MYSQL_PASSWORD=$(rand 32)
MYSQL_ROOT_PASSWORD=$(rand 32)
APP_TIMEZONE=${TIMEZONE}
LOG_LEVEL=INFO
GUNICORN_WORKERS=2
EOF
  chown "$DEPLOY_USER:$DEPLOY_USER" "$APP_DIR/.env"
  chmod 600 "$APP_DIR/.env"
  echo "Created $APP_DIR/.env with random secrets."
else
  echo "$APP_DIR/.env already exists; left unchanged."
fi

log "Done"
cat <<EOF
Server is ready. Next steps:
  * In GitHub: add the secrets DEPLOY_HOST, DEPLOY_USER (=$DEPLOY_USER), DEPLOY_SSH_KEY, DEPLOY_KNOWN_HOSTS
    and the variables DEPLOY_ENABLED=true and PUBLIC_URL (see README section 28).
  * Push to main (or re-run the latest workflow). GitHub Actions copies the
    deployment files into $APP_DIR and starts the stack.
  * Never run 'docker compose down -v' here: it deletes the database volume.
EOF
